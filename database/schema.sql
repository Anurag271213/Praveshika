-- =====================================================================
-- Login Feature — Database Schema (MySQL 8.0+)
-- Version: 1.0
-- Phase 2 — Technical Design
--
-- Important Security Notes:
--   1. Passwords are NEVER stored as plaintext. The `password_hash`
--      column stores only a BCrypt hash starting with "$2a$", "$2b$",
--      or "$2y$". The column name is intentionally NOT "password" so
--      accidental ORM mappings / toString() calls cannot leak secrets.
--   2. The `enabled` flag controls whether the account may be used to
--      authenticate (per Requirement-Spec §SEC-* and this phase brief).
--   3. Use the least-privilege DB account for the app connection. The
--      schema creation script below requires DDL privileges; the app
--      runtime user only needs SELECT/INSERT/UPDATE on `users`.
-- =====================================================================

